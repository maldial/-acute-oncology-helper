"""Deterministic routing: intent (+ safety) -> destination. No LLM routing."""
from app.agents.intent_agent import (
    ADMIN,
    CONFIRMATION,
    INFORMATION,
    SYMPTOM_REPORT,
    TEAM_MESSAGE,
    UNCLEAR,
)

CLINICAL_PIPELINE = "CLINICAL_PIPELINE"
CONFIRMATIONS_QUEUE = "CONFIRMATIONS_QUEUE"
ADMIN_QUEUE = "ADMIN_QUEUE"
INFO_QUEUE = "INFO_QUEUE"
FORWARD_QUEUE = "FORWARD_QUEUE"
CLARIFICATION = "CLARIFICATION"
SAFETY_ESCALATION = "SAFETY_ESCALATION"

INTENT_ROUTES = {
    SYMPTOM_REPORT: CLINICAL_PIPELINE,
    CONFIRMATION: CONFIRMATIONS_QUEUE,
    ADMIN: ADMIN_QUEUE,
    INFORMATION: INFO_QUEUE,
    TEAM_MESSAGE: FORWARD_QUEUE,
    UNCLEAR: CLARIFICATION,
}


def route(intent: str, safety_flagged: bool) -> str:
    if safety_flagged:
        return SAFETY_ESCALATION
    return INTENT_ROUTES.get(intent, CLARIFICATION)
